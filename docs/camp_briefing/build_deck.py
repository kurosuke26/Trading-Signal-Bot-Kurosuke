def _assemble():
    out = []
    for key in _ORDER:
        if key.startswith('@'):
            out.append(_EXTRA[key[1:]])
        else:
            hits = [d for d in _BASE if d['title'].startswith(key)]
            assert len(hits) == 1, key
            out.append(hits[0])
    assert len(out) == len({id(d) for d in out}) and len([d for d in _BASE if d in out]) == len(_BASE)
    return out


