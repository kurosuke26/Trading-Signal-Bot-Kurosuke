def render_table(slide, d, idx, total):
    _header(slide, d['title'], idx, total)
    rows = [d['header']] + d['rows']
    n = len(rows)
    height = min(0.62 * n, 5.0)
    widths = [2.4, 3.6, 6.1]
    if len(d['header'][0]) <= 3 and d['header'][0] != '時刻':
        widths = [2.2, 3.6, 6.3]
    gt = slide.shapes.add_table(n, 3, Inches(0.6), Inches(1.55), Inches(12.1), Inches(height)).table
    for c, w in enumerate(widths):
        gt.columns[c].width = Inches(w)
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = gt.cell(r, c)
            cell.fill.solid()
            cell.fill.fore_color.rgb = NAVY if r == 0 else (WHITE if r % 2 else LIGHT)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            tf = cell.text_frame
            tf.word_wrap = True
            tf.paragraphs[0].text = ''
            _text(tf, val, 16 if n <= 8 else 13, WHITE if r == 0 else INK, bold=(r == 0 or c == 0))
    if d.get('footer'):
        tf = _textbox(slide, 0.6, 6.45, 12.1, 0.5)
        _text(tf, d['footer'], 15, MUTED)


