def render_table(slide, d, idx, total):
    _header(slide, d['title'], idx, total)
    rows = [d['header']] + d['rows']
    n = len(rows)
    height = min(0.62 * n, 5.0)
    widths = [2.4, 3.6, 6.1]
    if len(d['header'][0]) <= 3 and d['header'][0] != '時刻':
        widths = [2.2, 3.6, 6.3]
    gt = slide.shapes.add_table(n, 3, Inches(0.6), Inches(1.55), Inches(12.1), Inches(height)).table
    for c, w in enumerate(widths):
        gt.columns[c].width = Inches(w)
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = gt.cell(r, c)
            cell.fill.solid()
            cell.fill.fore_color.rgb = NAVY if r == 0 else (WHITE if r % 2 else LIGHT)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            tf = cell.text_frame
            tf.word_wrap = True
            tf.paragraphs[0].text = ''
            _text(tf, val, 16, WHITE if r == 0 else INK, bold=(r == 0 or c == 0))
    if d.get('footer'):
        tf = _textbox(slide, 0.6, 1.75 + height, 12.1, 0.6)
        _text(tf, d['footer'], 15, MUTED)


def render_post(slide, d, idx, total):
    _header(slide, d['title'], idx, total)
    accent = ACCENTS[d.get('accent', 'green')]
    _box(slide, 0.6, 1.55, 7.9, 5.25, fill=DISCORD_BG)
    _box(slide, 0.6, 1.55, 0.09, 5.25, fill=accent)
    tf = _textbox(slide, 0.9, 1.75, 7.4, 4.9)
    for i, line in enumerate(d['post']):
        # 先頭が '#' の行は投稿内の見出し（太字・白）として描く
        is_head = line.startswith('#') or (i == 0 and not any(x.startswith('#') for x in d['post']))
        text = line.lstrip('#') if line else ' '
        p = _text(tf, text, 17 if is_head else 15,
                  WHITE if is_head else DISCORD_TXT, bold=is_head, first=(i == 0))
        p.space_before = Pt(12 if is_head and i else 6)
    tf = _textbox(slide, 8.85, 1.6, 4.0, 0.5)
    _text(tf, 'ここを見る', 18, accent, bold=True)
    tf = _textbox(slide, 8.85, 2.15, 4.0, 4.6)
    for i, line in enumerate(d['side']):
        p = _text(tf, line if line else ' ', 17, INK, first=(i == 0))
        p.space_before = Pt(8)


