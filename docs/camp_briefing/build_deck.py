def _text(frame, text, size, color=INK, bold=False, align=PP_ALIGN.LEFT, first=True):
    p = frame.paragraphs[0] if first else frame.add_paragraph()
    p.alignment = align
    r = p.add_run()
    r.text = text
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.color.rgb = color
    r.font.name = FONT
    return p


def _box(slide, x, y, w, h, fill=None, line=None, shape=MSO_SHAPE.RECTANGLE):
    s = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    if fill is None:
        s.fill.background()
    else:
        s.fill.solid()
        s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
    s.shadow.inherit = False
    return s


def _textbox(slide, x, y, w, h, anchor=MSO_ANCHOR.TOP):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    for m in ('margin_left', 'margin_right', 'margin_top', 'margin_bottom'):
        setattr(tf, m, Inches(0.05))
    return tf


def _header(slide, title, idx, total):
    _box(slide, 0, 0, 13.333, 0.12, fill=NAVY)
    tf = _textbox(slide, 0.6, 0.35, 12.1, 0.8, anchor=MSO_ANCHOR.MIDDLE)
    _text(tf, title, 28, NAVY, bold=True)
    _box(slide, 0.6, 1.2, 1.2, 0.06, fill=GREEN)
    ft = _textbox(slide, 0.6, 7.0, 12.1, 0.35)
    _text(ft, f'kurosuke式資産運用キャンプ　Bot活用説明会　　{idx}/{total}', 10, MUTED, align=PP_ALIGN.RIGHT)


def _bullet_list(slide, x, y, w, h, items, size=18):
    tf = _textbox(slide, x, y, w, h)
    for i, (text, level) in enumerate(items):
        if level == 0:
            p = _text(tf, '●  ' + text, size, INK, bold=True, first=(i == 0))
            p.space_before = Pt(20)
        elif level == 1:
            p = _text(tf, '　　' + text, size - 3, MUTED, first=(i == 0))
            p.space_before = Pt(2)
        else:
            p = _text(tf, '　　' + text, size - 2, INK, first=(i == 0))
            p.space_before = Pt(4)


